using UnityEngine;
using UnityEngine.UI;

/// <summary>
/// ゲーム全体の進行を管理するスクリプトです。
///
/// 主な機能：
///
/// ・ゲーム時間の進む速度を0～1で変更する
/// ・ゲームを開始する
/// ・00:00からタイマーをカウントアップする
/// ・指定した時間になったらゲームを終了する
/// ・ゲーム終了時にリザルト画面を表示する
/// ・タイトル画面に戻る
///
///
/// 【使用例】
///
/// ゲームを開始する：
/// GameManager.Instance.StartGame();
///
/// ゲームを終了する：
/// GameManager.Instance.EndGame();
///
/// タイトルに戻る：
/// GameManager.Instance.ReturnToTitle();
///
/// ゲームを停止する：
/// GameManager.Instance.SetGameTime(0f);
///
/// ゲームを通常速度にする：
/// GameManager.Instance.SetGameTime(1f);
/// </summary>
public class GameManager : MonoBehaviour
{
    // =========================================================
    // GameManagerをどこからでも呼び出せるようにする
    // =========================================================

    /// <summary>
    /// 他のスクリプトからGameManagerを呼び出すための変数です。
    ///
    /// 例えば、
    ///
    /// GameManager.Instance.StartGame();
    ///
    /// と書くことでゲームを開始できます。
    /// </summary>
    public static GameManager Instance { get; private set; }


    // =========================================================
    // Inspectorから設定する項目
    // =========================================================

    [Header("ゲーム時間設定")]

    [Tooltip("ゲーム開始から終了までの時間を秒数で指定します。例：60なら60秒でゲーム終了")]
    [SerializeField]
    private float gameDuration = 60f;


    [Header("タイマー表示")]

    [Tooltip("経過時間を表示するText（Legacy）を設定してください")]
    [SerializeField]
    private Text timerText;


    [Header("画面設定")]

    [Tooltip("ゲーム終了時に表示するリザルト画面を設定してください")]
    [SerializeField]
    private GameObject resultScreen;

    [Tooltip("ゲーム中に表示するUI群のGameObjectを設定してください")]
    [SerializeField]
    private GameObject uiGroup;

    [Tooltip("タイトル画面で表示するTitle群のGameObjectを設定してください")]
    [SerializeField]
    private GameObject titleGroup;


    // =========================================================
    // 内部で使用する変数
    // =========================================================

    /// <summary>
    /// ゲーム開始から何秒経過したかを保存します。
    ///
    /// ゲーム開始時は0秒です。
    ///
    /// 0 → 1 → 2 → 3……
    ///
    /// と増えていきます。
    /// </summary>
    private float elapsedTime = 0f;


    /// <summary>
    /// 現在ゲーム中かどうかを記録します。
    ///
    /// true  = ゲーム中
    /// false = ゲーム中ではない
    /// </summary>
    private bool isPlaying = false;


    // =========================================================
    // 初期化
    // =========================================================

    private void Awake()
    {
        // すでにGameManagerが存在する場合は、
        // 新しく作られたGameManagerを削除します。
        //
        // これによってGameManagerが複数存在することを防ぎます。
        if (Instance != null && Instance != this)
        {
            Destroy(gameObject);
            return;
        }


        // このGameManagerを
        // 現在使用するGameManagerとして登録します。
        Instance = this;
    }


    private void Start()
    {
        // ゲーム開始前なので
        // 経過時間を0秒にしておきます。
        elapsedTime = 0f;


        // タイマー表示を「00:00」に更新します。
        UpdateTimerText();
    }


    // =========================================================
    // ゲーム時間の設定
    // =========================================================

    /// <summary>
    /// ゲーム時間の進む速度を設定する関数です。
    ///
    /// 引数には0～1の値を指定します。
    ///
    /// 0   = ゲーム停止
    /// 0.5 = 半分の速度
    /// 1   = 通常速度
    ///
    ///
    /// 【使用例】
    ///
    /// GameManager.Instance.SetGameTime(0f);
    /// → ゲームを停止
    ///
    /// GameManager.Instance.SetGameTime(1f);
    /// → 通常速度
    /// </summary>
    public void SetGameTime(float value)
    {
        // 渡された数字を
        // 必ず0～1の範囲に収めます。
        //
        // 例えば、
        //
        // -1  → 0
        // 0.5 → 0.5
        // 2   → 1
        //
        // になります。
        value = Mathf.Clamp01(value);


        // Unity全体の時間の進む速度を変更します。
        //
        // 0なら停止、
        // 1なら通常速度です。
        Time.timeScale = value;
    }


    // =========================================================
    // ゲーム開始
    // =========================================================

    /// <summary>
    /// ゲームを開始する関数です。
    ///
    /// この関数を呼び出すと、
    ///
    /// ・リザルト画面を非表示
    /// ・UI群を表示
    /// ・Title群を非表示
    /// ・タイマーを00:00に戻す
    /// ・ゲーム時間を通常速度にする
    /// ・タイマーのカウントアップを開始
    ///
    /// します。
    ///
    ///
    /// 【使用例】
    ///
    /// GameManager.Instance.StartGame();
    /// </summary>
    public void StartGame()
    {
        // -----------------------------------------
        // リザルト画面を非表示にする
        // -----------------------------------------

        if (resultScreen != null)
        {
            resultScreen.SetActive(false);
        }


        // -----------------------------------------
        // ゲーム中のUI群を表示する
        // -----------------------------------------

        if (uiGroup != null)
        {
            uiGroup.SetActive(true);
        }


        // -----------------------------------------
        // Title群を非表示にする
        // -----------------------------------------

        if (titleGroup != null)
        {
            titleGroup.SetActive(false);
        }


        // -----------------------------------------
        // タイマーを00:00に戻す
        // -----------------------------------------

        // 経過時間を0秒に戻します。
        elapsedTime = 0f;


        // Textの表示も00:00に更新します。
        UpdateTimerText();


        // -----------------------------------------
        // ゲーム時間を通常速度にする
        // -----------------------------------------

        // ゲーム終了時にはTime.timeScaleが
        // 0になっている可能性があります。
        //
        // そのためゲーム開始時に1へ戻します。
        SetGameTime(1f);


        // -----------------------------------------
        // タイマーを開始する
        // -----------------------------------------

        // trueにすることで、
        // Update()内でタイマーが進むようになります。
        isPlaying = true;
    }


    // =========================================================
    // 毎フレーム実行する処理
    // =========================================================

    private void Update()
    {
        // ゲーム中でなければ
        // タイマーを進めません。
        if (!isPlaying)
        {
            return;
        }


        // -----------------------------------------
        // タイマーをカウントアップする
        // -----------------------------------------

        // Time.deltaTimeは、
        // 前のフレームから現在のフレームまでに
        // 経過した時間です。
        //
        // 毎フレーム足していくことで、
        //
        // 0秒 → 1秒 → 2秒 → 3秒……
        //
        // と時間が増えていきます。
        elapsedTime += Time.deltaTime;


        // -----------------------------------------
        // 制限時間になったか確認する
        // -----------------------------------------

        // Inspectorで設定したgameDuration以上になったら
        // ゲームを終了します。
        //
        // 例えばgameDurationが60なら、
        // 60秒経過した時点でゲーム終了です。
        if (elapsedTime >= gameDuration)
        {
            // 表示時間が設定時間を超えないように
            // gameDurationと同じ値にします。
            elapsedTime = gameDuration;


            // 最後のタイマー表示を更新します。
            UpdateTimerText();


            // ゲームを終了します。
            EndGame();

            return;
        }


        // 現在の経過時間を
        // Textに表示します。
        UpdateTimerText();
    }


    // =========================================================
    // タイマー表示
    // =========================================================

    /// <summary>
    /// 現在の経過時間を
    /// 「mm:ss」の形でText（Legacy）に表示します。
    ///
    /// 例：
    ///
    /// 0秒   → 00:00
    /// 5秒   → 00:05
    /// 30秒  → 00:30
    /// 60秒  → 01:00
    /// 125秒 → 02:05
    /// </summary>
    private void UpdateTimerText()
    {
        // InspectorにTextが設定されていない場合は
        // エラーを防ぐため処理を終了します。
        if (timerText == null)
        {
            return;
        }


        // 経過時間の小数点以下を切り捨てます。
        //
        // 例えば、
        //
        // 0.8秒  → 0秒
        // 5.7秒  → 5秒
        // 10.9秒 → 10秒
        //
        // となります。
        int totalSeconds = Mathf.FloorToInt(elapsedTime);


        // -----------------------------------------
        // 「分」を計算する
        // -----------------------------------------

        // 合計秒数を60で割ることで
        // 何分経過したかを求めます。
        //
        // 例えば125秒なら、
        //
        // 125 / 60 = 2
        //
        // なので2分です。
        int minutes = totalSeconds / 60;


        // -----------------------------------------
        // 「秒」を計算する
        // -----------------------------------------

        // % は割り算の余りを求めます。
        //
        // 例えば125秒なら、
        //
        // 125 % 60 = 5
        //
        // なので5秒です。
        int seconds = totalSeconds % 60;


        // -----------------------------------------
        // Textに表示する
        // -----------------------------------------

        // D2を指定すると数字が必ず2桁になります。
        //
        // 例えば、
        //
        // 0 → 00
        // 5 → 05
        // 30 → 30
        //
        // となります。
        //
        // そのため2分5秒なら
        //
        // 02:05
        //
        // と表示されます。
        timerText.text =
            minutes.ToString("D2")
            + ":"
            + seconds.ToString("D2");
    }


    // =========================================================
    // ゲーム終了
    // =========================================================

    /// <summary>
    /// ゲームを終了する関数です。
    ///
    /// この関数を呼び出すと、
    ///
    /// ・リザルト画面を表示
    /// ・UI群を非表示
    /// ・Title群を非表示
    /// ・タイマーを停止
    /// ・マウスカーソルを表示
    /// ・ゲーム時間を停止
    ///
    /// します。
    ///
    ///
    /// 【使用例】
    ///
    /// GameManager.Instance.EndGame();
    /// </summary>
    public void EndGame()
    {
        // -----------------------------------------
        // タイマーを停止する
        // -----------------------------------------

        // falseにすることで、
        // Update()内のタイマー処理を停止します。
        isPlaying = false;


        // -----------------------------------------
        // リザルト画面を表示する
        // -----------------------------------------

        if (resultScreen != null)
        {
            resultScreen.SetActive(true);
        }
        else
        {
            Debug.LogWarning(
                "GameManager：リザルト画面が設定されていません。"
            );
        }


        // -----------------------------------------
        // UI群を非表示にする
        // -----------------------------------------

        if (uiGroup != null)
        {
            uiGroup.SetActive(false);
        }
        else
        {
            Debug.LogWarning(
                "GameManager：UI群が設定されていません。"
            );
        }


        // -----------------------------------------
        // Title群を非表示にする
        // -----------------------------------------

        if (titleGroup != null)
        {
            titleGroup.SetActive(false);
        }
        else
        {
            Debug.LogWarning(
                "GameManager：Title群が設定されていません。"
            );
        }


        // -----------------------------------------
        // マウスカーソルを操作可能にする
        // -----------------------------------------

        // FPSなどで画面中央に固定されている
        // カーソルのロックを解除します。
        Cursor.lockState = CursorLockMode.None;


        // 非表示になっているカーソルを
        // 表示します。
        Cursor.visible = true;


        // -----------------------------------------
        // ゲーム時間を停止する
        // -----------------------------------------

        // Time.timeScaleを0にして
        // ゲーム全体の時間を停止します。
        SetGameTime(0f);
    }


    // =========================================================
    // タイトルに戻る
    // =========================================================

    /// <summary>
    /// タイトル画面に戻るための関数です。
    ///
    /// この関数を呼び出すと、
    ///
    /// ・ゲーム時間を通常速度に戻す
    /// ・リザルト画面を非表示
    /// ・UI群を非表示
    /// ・Title群を表示
    /// ・タイマーを停止
    /// ・タイマーを00:00に戻す
    ///
    /// します。
    ///
    ///
    /// リザルト画面の「タイトルへ戻る」ボタンなどから
    /// この関数を呼び出してください。
    ///
    ///
    /// 【使用例】
    ///
    /// GameManager.Instance.ReturnToTitle();
    /// </summary>
    public void ReturnToTitle()
    {
        // -----------------------------------------
        // ゲーム時間を通常速度に戻す
        // -----------------------------------------

        // ゲーム終了時にTime.timeScaleを0にしているため、
        // タイトルに戻るときに1へ戻します。
        SetGameTime(1f);


        // -----------------------------------------
        // タイマーを停止する
        // -----------------------------------------

        // タイトル画面ではゲーム中ではないため
        // タイマーを停止します。
        isPlaying = false;


        // -----------------------------------------
        // リザルト画面を非表示にする
        // -----------------------------------------

        if (resultScreen != null)
        {
            resultScreen.SetActive(false);
        }


        // -----------------------------------------
        // ゲーム中のUI群を非表示にする
        // -----------------------------------------

        if (uiGroup != null)
        {
            uiGroup.SetActive(false);
        }


        // -----------------------------------------
        // Title群を表示する
        // -----------------------------------------

        if (titleGroup != null)
        {
            titleGroup.SetActive(true);
        }
        else
        {
            Debug.LogWarning(
                "GameManager：Title群が設定されていません。"
            );
        }


        // -----------------------------------------
        // タイマーを00:00に戻す
        // -----------------------------------------

        elapsedTime = 0f;

        UpdateTimerText();


        // -----------------------------------------
        // カーソルを操作可能にする
        // -----------------------------------------

        // タイトル画面のボタンを操作できるように
        // カーソルのロックを解除します。
        Cursor.lockState = CursorLockMode.None;


        // カーソルを表示します。
        Cursor.visible = true;
    }
}